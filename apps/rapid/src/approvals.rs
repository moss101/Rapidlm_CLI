    #[test]
    fn durable_chain_query_returns_only_matching_approved_requests_after_reopen() {
        let path = std::env::temp_dir().join(format!(
            "rapidlm-chain-{}-{}.sqlite",
            std::process::id(),
            new_wait_token()
        ));
        let client = InProcessKernelClient::open(&path).unwrap();
        let actor = ActorRef::new(
            event_ledger::event::ActorKind::Human,
            &protocol::EventId::new().to_string(),
        )
        .unwrap();
        let session = client_call(client.create_session(kernel::CreateSession::new(
            protocol::ProjectId::new(),
            actor.clone(),
            protocol::TraceId::new(),
        )))
        .unwrap()
        .id();
        let sink =
            LedgerApprovalSink::new(client.clone(), session, actor.clone(), PathBuf::from("."));
        let prefix = "multi-edit:v1:nonce:fingerprint:";
        let digest = "a".repeat(64);
        for (index, decision, call_id) in [
            (0, Some(kernel::ApprovalDecision::Approved), "call"),
            (1, Some(kernel::ApprovalDecision::Denied), "call"),
            (2, None, "call"),
            (3, Some(kernel::ApprovalDecision::Approved), "other-call"),
        ] {
            let request = ApprovalRequest {
                tool: "workspace_multi_patch".into(),
                call_id: call_id.into(),
                summary: format!("file {index}"),
                scope: vec![format!("file-{index}")],
                diff: format!("diff {index}"),
                source: Some(format!("{prefix}{index}")),
                arguments_digest: Some(digest.clone()),
                remember_as: None,
            };
            let token = sink.request(&request).unwrap();
            if let Some(decision) = decision {
                let seq = client_call(client.get_session(session)).unwrap().seq();
                client_call(
                    client.approve(
                        kernel::ResolveApproval::new(
                            session,
                            seq,
                            decision,
                            actor.clone(),
                            protocol::TraceId::new(),
                        )
                        .with_wait_token(token),
                    ),
                )
                .unwrap();
            }
        }
        drop(sink);
        drop(client);
        let reopened = InProcessKernelClient::open(&path).unwrap();
        let sink = LedgerApprovalSink::new(reopened, session, actor, PathBuf::from("."));
        let found = sink
            .approved_chain_sources("call", "workspace_multi_patch", &digest, prefix)
            .unwrap();
        assert_eq!(found.len(), 1);
        assert_eq!(found[0].scope, vec!["file-0"]);
        assert_eq!(
            found[0].source.as_deref(),
            Some("multi-edit:v1:nonce:fingerprint:0")
        );
        assert!(
            sink.approved_chain_sources("call", "workspace_multi_patch", &digest, "invalid:")
                .is_err()
        );
        drop(sink);
        for suffix in ["", "-wal", "-shm", "-journal"] {
            let mut file = path.clone().into_os_string();
            file.push(suffix);
            let _ = std::fs::remove_file(file);
        }
    }

