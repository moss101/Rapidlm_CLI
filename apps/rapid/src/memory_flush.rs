    struct Tmp(PathBuf);

    impl Tmp {
        fn new(tag: &str) -> Self {
            let nanos = std::time::SystemTime::now()
                .duration_since(std::time::UNIX_EPOCH)
                .map(|d| d.as_nanos())
                .unwrap_or_default();
            let path = std::env::temp_dir().join(format!(
                "rapidlm-flush-{tag}-{}-{nanos}",
                std::process::id()
            ));
            std::fs::create_dir_all(&path).expect("temp dir");
            Self(path)
        }
    }

    impl Drop for Tmp {
        fn drop(&mut self) {
            let _ = std::fs::remove_dir_all(&self.0);
        }
    }

    fn a_proposal(text: &str, seqs: &[u64]) -> Proposal {
        Proposal {
            kind: Kind::Decision,
            text: text.to_owned(),
            evidence: seqs.to_vec(),
            confidence: 0.7,
        }
    }

    #[test]
    fn a_record_carries_its_evidence_and_session_and_is_not_written_twice() {
        let mut store = MemoryStore::open_in_memory(MemoryLimits::new()).expect("store");
        let project = project_id_for(Path::new("/some/project"));
        let session = protocol::SessionId::new();
        let proposals = [
            a_proposal("Use SQLite for the memory store.", &[3, 12]),
            Proposal {
                kind: Kind::Pattern,
                ..a_proposal("Run clippy before every commit.", &[5])
            },
        ];
        let first = apply(&mut store, project, session, &proposals).expect("applied");
        assert_eq!((first.written.len(), first.duplicates), (2, 0));
        assert_eq!(first.written[0].source().id(), "flush:decision:e3,12");
        assert_eq!(first.written[0].source().session_id(), Some(session));
        assert_eq!(first.written[1].source().id(), "flush:pattern:e5");
        assert_eq!(
            first.written[1].content(),
            "pattern: Run clippy before every commit."
        );
        assert_eq!(first.written[0].confidence(), 0.7);
        // The same again writes nothing new.
        let again = apply(&mut store, project, session, &proposals).expect("applied");
        assert_eq!((again.written.len(), again.duplicates), (0, 2));
        assert_eq!(
            store
                .retrieve_by_source_prefix(project, "flush:", 10)
                .expect("records")
                .len(),
            2
        );
        // Another project does not see them.
        let other = project_id_for(Path::new("/another/project"));
        assert!(
            store
                .retrieve_by_source_prefix(other, "flush:", 10)
                .expect("records")
                .is_empty()
        );
    }

    #[test]
    fn a_stored_record_is_made_inert_again_on_its_way_into_the_index() {
        let mut store = MemoryStore::open_in_memory(MemoryLimits::new()).expect("store");
        let project = project_id_for(Path::new("/some/project"));
        // Written past the proposal checks, as a hand-edited store could be.
        for (source, body) in [
            ("flush:decision:e1", "decision: keep\u{1b}[2J\nit tidy"),
            ("flush:decision:e2,x;rm", "decision: odd evidence field"),
            ("not-a-flush-record", "decision: someone else's record"),
        ] {
            store
                .write_memory(MemoryWrite::new(
                    MemoryScope::Project(project),
                    MemorySource::new(MemorySourceKind::Agent, source),
                    0.5,
                    body,
                ))
                .expect("write");
        }
        let lines = projection_lines(
            &store
                .retrieve_by_source_prefix(project, "", 10)
                .expect("records"),
        );
        assert_eq!(lines.len(), 2, "{lines:?}");
        let text = lines.join("\n");
        assert!(!text.contains('\u{1b}') && !text.contains("rm"), "{text:?}");
        assert!(text.contains("decision: keep [2J it tidy"), "{text}");
        assert!(!text.contains("someone else's"), "{text}");
    }

    #[test]
    fn the_index_is_created_updated_in_place_and_never_written_through_a_link() {
        // Missing: created with just the block; nothing left behind.
        let tmp = Tmp::new("index");
        let projection = write_projection(&tmp.0, &[]).expect("written");
        let file = tmp.0.join(".rapidlm").join("MEMORY.md");
        let text = std::fs::read_to_string(&file).expect("read");
        assert!(text.starts_with(PROJECTION_BEGIN), "{text}");
        assert!(!projection.beyond_window);
        let leftovers: Vec<_> = std::fs::read_dir(tmp.0.join(".rapidlm"))
            .expect("dir")
            .filter_map(Result::ok)
            .map(|entry| entry.file_name().to_string_lossy().into_owned())
            .collect();
        assert_eq!(leftovers, ["MEMORY.md"]);
        // Text that is not UTF-8, or too large, is refused, not rewritten.
        std::fs::write(&file, [0xff, 0xfe, b'x']).expect("write");
        let err = write_projection(&tmp.0, &[]).expect_err("refused");
        assert!(err.contains("not UTF-8"), "{err}");
        assert_eq!(std::fs::read(&file).expect("read"), [0xff, 0xfe, b'x']);
        std::fs::write(&file, vec![b'a'; MAX_MEMORY_FILE_BYTES + 1]).expect("write");
        let err = write_projection(&tmp.0, &[]).expect_err("refused");
        assert!(err.contains("too large"), "{err}");
        // A long hand-written file puts the block past what a turn loads.
        let long: String = (0..300).map(|n| format!("- note {n}\n")).collect();
        std::fs::write(&file, &long).expect("write");
        assert!(
            write_projection(&tmp.0, &[])
                .expect("written")
                .beyond_window
        );
        assert!(
            std::fs::read_to_string(&file)
                .expect("read")
                .starts_with(&long)
        );
    }

    #[cfg(unix)]
    #[test]
    fn a_linked_index_or_directory_is_refused() {
        let tmp = Tmp::new("links");
        let outside = Tmp::new("outside");
        std::fs::write(outside.0.join("victim.txt"), "keep me").expect("write");
        // MEMORY.md a link to a file elsewhere.
        std::fs::create_dir_all(tmp.0.join(".rapidlm")).expect("dir");
        std::os::unix::fs::symlink(
            outside.0.join("victim.txt"),
            tmp.0.join(".rapidlm").join("MEMORY.md"),
        )
        .expect("link");
        let err = write_projection(&tmp.0, &[]).expect_err("refused");
        assert!(err.contains("not a plain file or directory"), "{err}");
        assert_eq!(
            std::fs::read_to_string(outside.0.join("victim.txt")).expect("read"),
            "keep me"
        );
        // `.rapidlm` itself a link to a directory elsewhere.
        let tmp2 = Tmp::new("dirlink");
        std::os::unix::fs::symlink(&outside.0, tmp2.0.join(".rapidlm")).expect("link");
        assert!(write_projection(&tmp2.0, &[]).is_err());
        assert!(!outside.0.join("MEMORY.md").exists());
    }

