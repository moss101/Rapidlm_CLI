    #[test]
    fn the_block_replaces_only_itself_and_leaves_the_rest_byte_for_byte() {
        let block = format!("{PROJECTION_BEGIN}\nnew\n{PROJECTION_END}\n");
        let old_block = format!("{PROJECTION_BEGIN}\nold\n{PROJECTION_END}\n");
        // No block yet: appended after a blank line; a file without a final
        // newline gets one.
        assert_eq!(merge_projection("", &block), block);
        assert_eq!(
            merge_projection("# Notes\n- mine", &block),
            format!("# Notes\n- mine\n\n{block}")
        );
        // A block: replaced in place; text before and after untouched.
        let file = format!("# Notes\r\n- mine\n\n{old_block}\ntrailing text  \n");
        assert_eq!(
            merge_projection(&file, &block),
            format!("# Notes\r\n- mine\n\n{block}\ntrailing text  \n")
        );
        // Regenerating is idempotent.
        let once = merge_projection(&file, &block);
        assert_eq!(merge_projection(&once, &block), once);
        // A begin marker with no end is not a block: it is left alone.
        let broken = format!("keep\n{PROJECTION_BEGIN}\nhalf\n");
        let merged = merge_projection(&broken, &block);
        assert!(merged.starts_with(&broken), "{merged}");
        assert!(merged.ends_with(&block));
    }
