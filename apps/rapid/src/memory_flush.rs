    #[test]
    fn a_reply_is_read_strictly_and_only_real_evidence_counts() {
        let reply = r#"Here you go:
```json
[
 {"kind":"decision","text":"Use SQLite for the memory store.","evidence":[3,5],"confidence":0.9},
 {"kind":"Pattern","text":"Run clippy before every commit.","evidence":[5]},
 {"kind":"decision","text":"Cites an event that does not exist.","evidence":[99]},
 {"kind":"decision","text":"Cites nothing at all here.","evidence":[]},
 {"kind":"opinion","text":"An unknown kind of record.","evidence":[3]},
 {"kind":"decision","text":"short","evidence":[3]},
 {"kind":"decision","text":"A partly bad evidence list.","evidence":[3,"x"]},
 {"kind":"decision","text":"Use SQLite for the memory store.","evidence":[3]},
 {"kind":"decision","text":"An unusable confidence value.","evidence":[3],"confidence":"high"}
]
```"#;
        let parsed = parse_proposals(reply, &valid(&[3, 5, 7]));
        assert_eq!(parsed.proposals.len(), 2, "{parsed:?}");
        assert_eq!(parsed.proposals[0].kind, Kind::Decision);
        assert_eq!(parsed.proposals[0].evidence, vec![3, 5]);
        assert_eq!(parsed.proposals[0].confidence, 0.9);
        assert_eq!(parsed.proposals[1].kind, Kind::Pattern);
        assert_eq!(parsed.proposals[1].confidence, 0.6);
        assert_eq!(parsed.refused.len(), 7, "{:?}", parsed.refused);
        assert!(
            parsed
                .refused
                .contains(&"a proposal cited an event that is not in the digest")
        );
        // Not an array, or not JSON: nothing, and it says so.
        for bad in ["[]x", "no json here", "{\"kind\":\"decision\"}", "]["] {
            let parsed = parse_proposals(bad, &valid(&[1]));
            assert!(parsed.proposals.is_empty(), "{bad}");
        }
        assert!(parse_proposals("[]", &valid(&[1])).refused.is_empty());
    }

