//! Validated recovery records for a future durable multi-file transaction.
//!
//! This module plans recovery only. It does not persist records, resolve host
//! paths, acquire locks, or apply filesystem changes. Callers must do those
//! things before exposing a multi-file commit.
use std::collections::{BTreeMap, BTreeSet};

use protocol::RepoPath;
use serde::{Deserialize, Serialize};

pub const MAX_RECOVERY_FILES: usize = 32;
pub const MAX_RECOVERY_BYTES: usize = 16 * 1024 * 1024;
pub const MAX_RECOVERY_JSON_BYTES: usize = MAX_RECOVERY_BYTES * 4 + 1024 * 1024;
const SCHEMA: &str = "rapidlm.multi_edit_recovery";
const VERSION: u16 = 1;

/// An exact file image, including portable permission bits where available.
#[derive(Clone, Debug, Eq, PartialEq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct FileImage {
    pub bytes: Vec<u8>,
    pub mode: Option<u32>,
}

/// One confined workspace path and its original and intended final images.
#[derive(Clone, Debug, Eq, PartialEq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct RecoveryEntry {
    pub path: String,
    pub before: Option<FileImage>,
    pub after: Option<FileImage>,
}

/// An intent requires rollback. A committed record requires verification of
/// all postimages and must never silently roll a completed commit back.
#[derive(Clone, Copy, Debug, Eq, PartialEq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum RecoveryState {
    Intent,
    Committed,
}

#[derive(Clone, Debug, Eq, PartialEq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct RecoveryRecord {
    schema: String,
    version: u16,
    state: RecoveryState,
    entries: Vec<RecoveryEntry>,
    /// Optional journal-first staging plan. Older version-1 records omit it.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    staging: Option<StagingPlan>,
}

/// OS identity observed after exclusive creation and durably recorded before
/// any candidate bytes are written. A missing identity does not authorize
/// deleting an existing path during recovery.
#[derive(Clone, Copy, Debug, Eq, PartialEq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct StageIdentity {
    pub device: u64,
    pub inode: u64,
}

#[derive(Clone, Debug, Eq, PartialEq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
struct StagingPlan {
    transaction_id: String,
    identities: Vec<Option<StageIdentity>>,
}

#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum RecoveryError {
    InvalidRecord,
    BoundExceeded,
    MissingObservation,
    Conflict,
}

/// A decision is advisory until the caller locks the path, checks its exact
/// current image again, and applies the operation with confinement enforced.
#[derive(Clone, Debug, Eq, PartialEq)]
pub enum RecoveryAction {
    AlreadyOriginal {
        path: String,
    },
    Restore {
        path: String,
        before: Option<FileImage>,
    },
    Committed {
        path: String,
    },
    Conflict {
        path: String,
    },
}

impl RecoveryRecord {
    pub fn state(&self) -> RecoveryState {
        self.state
    }

    pub fn entries(&self) -> &[RecoveryEntry] {
        &self.entries
    }

    /// Install the unpredictable 128-bit identifier generated by the host
    /// before publishing intent. File names are derived, never user-supplied.
    pub fn with_staging_plan(mut self, transaction_id: String) -> Result<Self, RecoveryError> {
        if self.state != RecoveryState::Intent || self.staging.is_some() {
            return Err(RecoveryError::InvalidRecord);
        }
        self.staging = Some(StagingPlan {
            transaction_id,
            identities: vec![None; self.entries.len()],
        });
        self.validate()?;
        Ok(self)
    }

    pub fn staging_name(&self, index: usize) -> Option<String> {
        let entry = self.entries.get(index)?;
        entry.after.as_ref()?;
        let plan = self.staging.as_ref()?;
        Some(format!(".rapidlm-stage-{}-{index}", plan.transaction_id))
    }

    pub fn has_staging_plan(&self) -> bool {
        self.staging.is_some()
    }

    pub fn stage_identity(&self, index: usize) -> Option<StageIdentity> {
        *self.staging.as_ref()?.identities.get(index)?
    }

    pub fn is_commit_of(&self, intent: &Self) -> bool {
        if intent.state != RecoveryState::Intent || self.state != RecoveryState::Committed {
            return false;
        }
        let mut expected = intent.clone();
        expected.state = RecoveryState::Committed;
        self == &expected
    }

    /// Return the only permitted next registration; callers must durably
    /// publish it before writing bytes into the newly created empty file.
    pub fn register_stage(
        &self,
        index: usize,
        identity: StageIdentity,
    ) -> Result<Self, RecoveryError> {
        self.validate()?;
        if self.state != RecoveryState::Intent
            || identity.inode == 0
            || self.staging_name(index).is_none()
        {
            return Err(RecoveryError::InvalidRecord);
        }
        let mut next = self.clone();
        let slot = next
            .staging
            .as_mut()
            .ok_or(RecoveryError::InvalidRecord)?
            .identities
            .get_mut(index)
            .ok_or(RecoveryError::InvalidRecord)?;
        if slot.is_some() {
            return Err(RecoveryError::Conflict);
        }
        *slot = Some(identity);
        next.validate()?;
        Ok(next)
    }

    /// Prepare a committed record only after observing every postimage.
    /// The caller must hold all write locks through this check and durable
    /// record update; observations alone do not make the transition atomic.
    pub fn committed(
        &self,
        current: &BTreeMap<String, Option<FileImage>>,
    ) -> Result<Self, RecoveryError> {
        self.validate()?;
        for entry in &self.entries {
            let observed = current
                .get(&entry.path)
                .ok_or(RecoveryError::MissingObservation)?;
            if observed != &entry.after {
                return Err(RecoveryError::Conflict);
            }
        }
        let mut committed = self.clone();
        committed.state = RecoveryState::Committed;
        Ok(committed)
    }

    pub fn new(state: RecoveryState, entries: Vec<RecoveryEntry>) -> Result<Self, RecoveryError> {
        let record = Self {
            schema: SCHEMA.to_owned(),
            version: VERSION,
            state,
            entries,
            staging: None,
        };
        record.validate()?;
        Ok(record)
    }

    pub fn decode(bytes: &[u8]) -> Result<Self, RecoveryError> {
        if bytes.len() > MAX_RECOVERY_JSON_BYTES {
            return Err(RecoveryError::BoundExceeded);
        }
        let record: Self =
            serde_json::from_slice(bytes).map_err(|_| RecoveryError::InvalidRecord)?;
        record.validate()?;
        Ok(record)
    }

    pub fn encode(&self) -> Result<Vec<u8>, RecoveryError> {
        self.validate()?;
        let bytes = serde_json::to_vec(self).map_err(|_| RecoveryError::InvalidRecord)?;
        if bytes.len() > MAX_RECOVERY_JSON_BYTES {
            return Err(RecoveryError::BoundExceeded);
        }
        Ok(bytes)
    }

    fn validate(&self) -> Result<(), RecoveryError> {
        if self.schema != SCHEMA
            || self.version != VERSION
            || self.entries.is_empty()
            || self.entries.len() > MAX_RECOVERY_FILES
        {
            return Err(RecoveryError::InvalidRecord);
        }
        if let Some(plan) = &self.staging
            && (plan.transaction_id.len() != 32
                || !plan
                    .transaction_id
                    .bytes()
                    .all(|byte| byte.is_ascii_digit() || (b'a'..=b'f').contains(&byte))
                || plan.identities.len() != self.entries.len()
                || plan.identities.iter().enumerate().any(|(index, identity)| {
                    identity.is_some_and(|id| id.inode == 0 || self.entries[index].after.is_none())
                }))
        {
            return Err(RecoveryError::InvalidRecord);
        }
        let mut seen = BTreeSet::new();
        let mut bytes = 0usize;
        for entry in &self.entries {
            let path = RepoPath::parse(&entry.path).map_err(|_| RecoveryError::InvalidRecord)?;
            if path.as_str() != entry.path
                || path
                    .components()
                    .any(|c| c.eq_ignore_ascii_case(".git") || c.eq_ignore_ascii_case(".rapidlm"))
                || !seen.insert(entry.path.as_str())
                || entry.before == entry.after
            {
                return Err(RecoveryError::InvalidRecord);
            }
            for image in [&entry.before, &entry.after].into_iter().flatten() {
                if image.mode.is_some_and(|mode| mode > 0o7777) {
                    return Err(RecoveryError::InvalidRecord);
                }
                bytes = bytes
                    .checked_add(image.bytes.len())
                    .ok_or(RecoveryError::BoundExceeded)?;
                if bytes > MAX_RECOVERY_BYTES {
                    return Err(RecoveryError::BoundExceeded);
                }
            }
        }
        let paths: Vec<String> = seen.into_iter().map(str::to_ascii_lowercase).collect();
        for (index, path) in paths.iter().enumerate() {
            for other in paths.iter().skip(index + 1) {
                if path == other
                    || path
                        .strip_prefix(other)
                        .is_some_and(|rest| rest.starts_with('/'))
                    || other
                        .strip_prefix(path)
                        .is_some_and(|rest| rest.starts_with('/'))
                {
                    return Err(RecoveryError::InvalidRecord);
                }
            }
        }
        Ok(())
    }

    /// Decide what recovery would do against complete, fresh observations.
    /// Rollback actions run in reverse publication order. Unexpected bytes or
    /// permissions are conflicts: they must not be overwritten automatically.
    pub fn plan(
        &self,
        current: &BTreeMap<String, Option<FileImage>>,
    ) -> Result<Vec<RecoveryAction>, RecoveryError> {
        self.validate()?;
        if self
            .entries
            .iter()
            .any(|entry| !current.contains_key(&entry.path))
        {
            return Err(RecoveryError::MissingObservation);
        }
        let mut actions = Vec::with_capacity(self.entries.len());
        for entry in self.entries.iter().rev() {
            let observed = &current[&entry.path];
            let path = entry.path.clone();
            let action = match self.state {
                RecoveryState::Intent if observed == &entry.before => {
                    RecoveryAction::AlreadyOriginal { path }
                }
                RecoveryState::Intent if observed == &entry.after => RecoveryAction::Restore {
                    path,
                    before: entry.before.clone(),
                },
                RecoveryState::Committed if observed == &entry.after => {
                    RecoveryAction::Committed { path }
                }
                _ => RecoveryAction::Conflict { path },
            };
            actions.push(action);
        }
        Ok(actions)
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn staging_plan_rejects_unsafe_ids_and_invalid_registrations() {
        let record = RecoveryRecord::new(RecoveryState::Intent, entries()).unwrap();
        assert_eq!(
            record.clone().with_staging_plan("../unsafe".into()),
            Err(RecoveryError::InvalidRecord)
        );
        let plan = record
            .with_staging_plan("0123456789abcdef0123456789abcdef".into())
            .unwrap();
        assert_eq!(
            plan.staging_name(0).as_deref(),
            Some(".rapidlm-stage-0123456789abcdef0123456789abcdef-0")
        );
        assert_eq!(
            plan.register_stage(
                0,
                StageIdentity {
                    device: 1,
                    inode: 0
                }
            ),
            Err(RecoveryError::InvalidRecord)
        );
        assert_eq!(
            plan.register_stage(
                99,
                StageIdentity {
                    device: 1,
                    inode: 2
                }
            ),
            Err(RecoveryError::InvalidRecord)
        );
        let encoded = plan.encode().unwrap();
        assert_eq!(RecoveryRecord::decode(&encoded).unwrap(), plan);
        let mut malformed: serde_json::Value = serde_json::from_slice(&encoded).unwrap();
        malformed["staging"]["identities"] = serde_json::json!([]);
        assert_eq!(
            RecoveryRecord::decode(&serde_json::to_vec(&malformed).unwrap()),
            Err(RecoveryError::InvalidRecord)
        );
    }
    fn image(s: &str, mode: u32) -> Option<FileImage> {
        Some(FileImage {
            bytes: s.as_bytes().to_vec(),
            mode: Some(mode),
        })
    }
    fn entries() -> Vec<RecoveryEntry> {
        vec![
            RecoveryEntry {
                path: "a.txt".into(),
                before: image("a0", 0o644),
                after: image("a1", 0o644),
            },
            RecoveryEntry {
                path: "new.txt".into(),
                before: None,
                after: image("new", 0o600),
            },
        ]
    }
    #[test]
    fn interrupted_publication_plans_reverse_restoration_and_preserves_conflicts() {
        let record = RecoveryRecord::new(RecoveryState::Intent, entries()).unwrap();
        let encoded = record.encode().unwrap();
        let record = RecoveryRecord::decode(&encoded).unwrap();
        let current = BTreeMap::from([
            ("a.txt".into(), image("a1", 0o644)),
            ("new.txt".into(), image("new", 0o600)),
        ]);
        assert_eq!(
            record.plan(&current).unwrap(),
            vec![
                RecoveryAction::Restore {
                    path: "new.txt".into(),
                    before: None
                },
                RecoveryAction::Restore {
                    path: "a.txt".into(),
                    before: image("a0", 0o644)
                }
            ]
        );
        let current = BTreeMap::from([
            ("a.txt".into(), image("a1", 0o600)),
            ("new.txt".into(), None),
        ]);
        assert_eq!(
            record.plan(&current).unwrap(),
            vec![
                RecoveryAction::AlreadyOriginal {
                    path: "new.txt".into()
                },
                RecoveryAction::Conflict {
                    path: "a.txt".into()
                }
            ]
        );
    }
    #[test]
    fn committed_recovery_reports_changed_or_missing_files_as_conflicts() {
        let record = RecoveryRecord::new(RecoveryState::Committed, entries()).unwrap();
        let current = BTreeMap::from([
            ("a.txt".into(), image("a1", 0o644)),
            ("new.txt".into(), None),
        ]);
        assert_eq!(
            record.plan(&current).unwrap(),
            vec![
                RecoveryAction::Conflict {
                    path: "new.txt".into()
                },
                RecoveryAction::Committed {
                    path: "a.txt".into()
                }
            ]
        );
        assert_eq!(
            record.plan(&BTreeMap::new()),
            Err(RecoveryError::MissingObservation)
        );
    }
    #[test]
    fn commit_record_requires_every_postimage() {
        let record = RecoveryRecord::new(RecoveryState::Intent, entries()).unwrap();
        let current = BTreeMap::from([
            ("a.txt".into(), image("a1", 0o644)),
            ("new.txt".into(), None),
        ]);
        assert_eq!(record.committed(&current), Err(RecoveryError::Conflict));
        assert_eq!(record.state(), RecoveryState::Intent);
        let current = BTreeMap::from([
            ("a.txt".into(), image("a1", 0o644)),
            ("new.txt".into(), image("new", 0o600)),
        ]);
        let committed = record.committed(&current).unwrap();
        assert_eq!(committed.state(), RecoveryState::Committed);
        assert_eq!(committed.entries(), record.entries());
    }
    #[test]
    fn records_reject_ambiguous_paths_duplicates_unknown_fields_and_bounds() {
        for path in [
            "../outside",
            "a//b",
            "a\\b",
            ".git/config",
            ".rapidlm/state",
        ] {
            let mut items = entries();
            items[0].path = path.into();
            assert_eq!(
                RecoveryRecord::new(RecoveryState::Intent, items),
                Err(RecoveryError::InvalidRecord)
            );
        }
        let mut items = entries();
        items[1].path = items[0].path.clone();
        assert_eq!(
            RecoveryRecord::new(RecoveryState::Intent, items),
            Err(RecoveryError::InvalidRecord)
        );
        for (first, second) in [("a", "a/child"), ("A.txt", "a.TXT"), ("a", "A/b")] {
            let mut items = entries();
            items[0].path = first.into();
            items[1].path = second.into();
            assert_eq!(
                RecoveryRecord::new(RecoveryState::Intent, items),
                Err(RecoveryError::InvalidRecord)
            );
        }
        let record = RecoveryRecord::new(RecoveryState::Intent, entries()).unwrap();
        let mut wire: serde_json::Value =
            serde_json::from_slice(&record.encode().unwrap()).unwrap();
        wire["unexpected"] = true.into();
        assert_eq!(
            RecoveryRecord::decode(&serde_json::to_vec(&wire).unwrap()),
            Err(RecoveryError::InvalidRecord)
        );
        let mut wire: serde_json::Value =
            serde_json::from_slice(&record.encode().unwrap()).unwrap();
        wire["version"] = 2.into();
        assert_eq!(
            RecoveryRecord::decode(&serde_json::to_vec(&wire).unwrap()),
            Err(RecoveryError::InvalidRecord)
        );
        assert_eq!(
            RecoveryRecord::decode(&vec![0; MAX_RECOVERY_JSON_BYTES + 1]),
            Err(RecoveryError::BoundExceeded)
        );
    }
}
