/**
 * @param {string} generated
 * @param {boolean} check
 */
function emit(generated, check) {
  if (!generated.endsWith("\n")) {
    generated += "\n";
  }
  if (check) {
    let existing = "";
    try {
      existing = readFileSync(OUT_PATH, "utf8");
    } catch {
      console.error(`missing generated file ${OUT_PATH}`);
      process.exit(1);
    }
    if (existing !== generated) {
      console.error("generated TypeScript wire types differ from schemas/wire.v1.json");
      process.exit(1);
    }
    return;
  }
  mkdirSync(dirname(OUT_PATH), { recursive: true });
  writeFileSync(OUT_PATH, generated);
}

const catalog = loadCatalog(SCHEMA_PATH);
const generated = render(catalog);
const check = process.argv.includes("--check");
emit(generated, check);
if (!check) {
  process.stdout.write(`wrote ${OUT_PATH}\n`);
}
