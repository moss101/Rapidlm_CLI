/**
 * @param {string} path
 * @returns {object}
 */
function loadCatalog(path) {
  const raw = readFileSync(path, "utf8");
  if (raw.includes("\r")) {
    throw new Error(`${path} must use LF newlines`);
  }
  const catalog = JSON.parse(raw);
  if (catalog.schema !== "rapidlm.sdk.wire" || catalog.schema_version !== 1) {
    throw new Error("unsupported wire catalog schema");
  }
  return catalog;
}

/**
 * @param {unknown} value
 * @returns {string}
 */
function stableJson(value) {
  return `${JSON.stringify(value, null, 2)}\n`;
}

/**
 * @param {string[]} values
 * @returns {string}
 */
function unionLiterals(values) {
  return values.map((value) => `"${value}"`).join("\n  | ");
}

/**
 * @param {string[]} values
 * @returns {string}
 */
function constArray(values) {
  return values.map((value) => `  "${value}",`).join("\n");
}

/**
 * @param {object} catalog
 * @returns {string}
 */
