  const eventKinds = catalog.event_kinds;
  const tools = catalog.tools;
  const b = catalog.bounds;
  const retryableCodes = errorCodes
    .filter((entry) => entry.retryable)
    .map((entry) => entry.code);
  const nonRetryableCodes = errorCodes
    .filter((entry) => !entry.retryable)
    .map((entry) => entry.code);

  const errorVariants = errorCodes
    .map(
      (entry) =>
        `  | {\n      code: "${entry.code}";\n      message: string;\n      retryable: ${entry.retryable};\n      trace_id: Uuid;\n      details: ErrorDetails;\n    }`,
    )
    .join("\n");

  const eventVariants = eventKinds
    .map(
      (entry) =>
        `  | EventEnvelope<"${entry.kind}", JsonValue>`,
    )
    .join("\n");

  const sessionVariants = catalog.session_statuses
    .map((status) => `  | SessionSnapshot<"${status}">`)
    .join("\n");

  const agentVariants = catalog.agent_states
    .map((state) => {
      const terminal = catalog.agent_terminal_statuses.includes(state);
      return `  | AgentRecord<"${state}", ${terminal ? "AgentResult" : "null"}>`;
    })
    .join("\n");

  const goalVariants = catalog.goal_states
    .map((state) => `  | GoalSnapshot<"${state}">`)
    .join("\n");

  const toolVariants = tools
    .map((tool) => `  | ToolCall<"${tool.name}">`)
    .join("\n");

  const toolResultVariants = catalog.tool_result_statuses
    .map((status) => `  | ToolResult<"${status}">`)
    .join("\n");

  const eventKindToFamily = eventKinds
    .map((entry) => `  "${entry.kind}": "${entry.family}",`)
    .join("\n");

  const errorRetryable = errorCodes
    .map((entry) => `  "${entry.code}": ${entry.retryable},`)
    .join("\n");

