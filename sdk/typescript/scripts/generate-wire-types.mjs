export function decodeAgent(input: unknown, options?: DecodeOptions): Agent {
  const ctx = beginDecode(input, options);
  const obj = expectObject(input, "");
  rejectUnknownFields(obj, ["spec", "state", "stats", "result"], "");
  const spec = decodeAgentSpec(expectField(obj, "spec", ""), options);
  const state = asClosed(expectField(obj, "state", ""), AGENT_STATES, "state");
  const terminal = (AGENT_TERMINAL_STATUSES as readonly string[]).includes(state);
  const result = asOptionalNull(obj.result, "result", (inner) => decodeAgentResult(inner, options));
  if (terminal && result === null) {
    fail("malformed", "result", "terminal agent state requires a result");
  }
  if (!terminal && result !== null) {
    fail("malformed", "result", "non-terminal agent state cannot carry a result");
  }
  if (result !== null && result.agent_id !== spec.id) {
    fail("malformed", "result.agent_id", "agent result id does not match spec");
  }
  visit(ctx);
  return {
    spec,
    state,
    stats: decodeAgentStats(expectField(obj, "stats", ""), "stats"),
    result,
  } as Agent;
}

